    /**
     * Ensures every drone's status strictly reflects active missions:
     * - A drone assigned to an 'In Progress' mission MUST be 'On Mission'
     * - Drones without active missions return to 'Available' (unless Charging or Maintenance)
     */
    public void syncDroneStatuses() {
        try {
            // Mark drones on in-progress missions as 'On Mission'
            exec("""
                UPDATE drone
                SET status = 'On Mission'
                WHERE droneid IN (
                    SELECT droneid FROM mission
                    WHERE missionstatus = 'In Progress' AND droneid IS NOT NULL
                )
            """);

            // Free drones whose missions are Completed or Aborted (if currently marked On Mission)
            exec("""
                UPDATE drone
                SET status = 'Available'
                WHERE status = 'On Mission'
                  AND droneid NOT IN (
                    SELECT droneid FROM mission
                    WHERE missionstatus = 'In Progress' AND droneid IS NOT NULL
                )
            """);
        } catch (Exception e) {
            log.warn("Status synchronization notice: {}", e.getMessage());
        }
    }
