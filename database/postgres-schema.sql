-- PostgreSQL schema for AeroRescue Disaster Operations DBMS
-- Compatible with Neon, Supabase, Render, and standard PostgreSQL

CREATE TABLE IF NOT EXISTS operator (
    operatorid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(60) NOT NULL,
    lastname VARCHAR(60),
    licenseno VARCHAR(60) UNIQUE NOT NULL,
    contactphone VARCHAR(30),
    status VARCHAR(30) DEFAULT 'AVAILABLE'
);

CREATE TABLE IF NOT EXISTS location (
    locationid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    areaname VARCHAR(100) NOT NULL,
    district VARCHAR(80),
    state VARCHAR(80),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6)
);

CREATE TABLE IF NOT EXISTS disaster (
    disasterid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disastername VARCHAR(100) NOT NULL,
    startdate DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'Active',
    locationid BIGINT REFERENCES location(locationid)
);

CREATE TABLE IF NOT EXISTS relief_camp (
    campid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campname VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    contactno VARCHAR(30),
    location VARCHAR(120)
);

ALTER TABLE relief_camp ADD COLUMN IF NOT EXISTS location VARCHAR(120);

CREATE TABLE IF NOT EXISTS drone (
    droneid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(80) NOT NULL,
    manufacturer VARCHAR(80) NOT NULL DEFAULT 'AeroRescue',
    payloadcapacity NUMERIC(7,2) NOT NULL DEFAULT 15.0 CHECK (payloadcapacity >= 0),
    maxflighttime INTEGER NOT NULL DEFAULT 45 CHECK (maxflighttime > 0),
    batterylevel INTEGER CHECK (batterylevel BETWEEN 0 AND 100),
    status VARCHAR(30) NOT NULL DEFAULT 'Available',
    operatorid BIGINT REFERENCES operator(operatorid)
);

-- Safe column migrations for pre-existing tables
ALTER TABLE drone ADD COLUMN IF NOT EXISTS manufacturer VARCHAR(80) NOT NULL DEFAULT 'AeroRescue';
ALTER TABLE drone ADD COLUMN IF NOT EXISTS payloadcapacity NUMERIC(7,2) NOT NULL DEFAULT 15.0;
ALTER TABLE drone ADD COLUMN IF NOT EXISTS maxflighttime INTEGER NOT NULL DEFAULT 45;
ALTER TABLE drone ADD COLUMN IF NOT EXISTS batterylevel INTEGER DEFAULT 100;
ALTER TABLE drone ADD COLUMN IF NOT EXISTS status VARCHAR(30) NOT NULL DEFAULT 'Available';
ALTER TABLE drone DROP CONSTRAINT IF EXISTS drone_status_check;

CREATE TABLE IF NOT EXISTS victim (
    victimid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    victimname VARCHAR(100) NOT NULL,
    dateofbirth DATE,
    gender CHAR(1) CHECK (gender IN ('M', 'F', 'O')),
    medicalpriority VARCHAR(20) DEFAULT 'High',
    currentstatus VARCHAR(30) NOT NULL DEFAULT 'Missing',
    disasterid BIGINT REFERENCES disaster(disasterid),
    campid BIGINT REFERENCES relief_camp(campid) ON DELETE SET NULL,
    emergencydetails TEXT
);

CREATE TABLE IF NOT EXISTS mission (
    missionid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    missiontype VARCHAR(40) NOT NULL DEFAULT 'Rescue',
    missiondate DATE NOT NULL DEFAULT CURRENT_DATE,
    priority VARCHAR(20) NOT NULL DEFAULT 'Medium',
    missionstatus VARCHAR(30) NOT NULL DEFAULT 'In Progress',
    disasterid BIGINT REFERENCES disaster(disasterid),
    droneid BIGINT REFERENCES drone(droneid),
    operatorid BIGINT REFERENCES operator(operatorid),
    location VARCHAR(120),
    notes TEXT
);

ALTER TABLE mission ADD COLUMN IF NOT EXISTS priority VARCHAR(20) NOT NULL DEFAULT 'Medium';
ALTER TABLE mission ADD COLUMN IF NOT EXISTS location VARCHAR(120);
ALTER TABLE mission ADD COLUMN IF NOT EXISTS notes TEXT;

CREATE TABLE IF NOT EXISTS supply (
    supplyid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplytype VARCHAR(100) NOT NULL,
    quantityavailable INTEGER NOT NULL DEFAULT 0 CHECK (quantityavailable >= 0),
    campid BIGINT REFERENCES relief_camp(campid),
    unit VARCHAR(30) DEFAULT 'units',
    lastupdated VARCHAR(40)
);

ALTER TABLE supply ADD COLUMN IF NOT EXISTS unit VARCHAR(30) DEFAULT 'units';
ALTER TABLE supply ADD COLUMN IF NOT EXISTS lastupdated VARCHAR(40);

CREATE TABLE IF NOT EXISTS organization (
    orgid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orgname VARCHAR(120) NOT NULL,
    orgtype VARCHAR(60) NOT NULL,
    headoffice VARCHAR(120),
    contactemail VARCHAR(100),
    contactphone VARCHAR(30)
);

DROP VIEW IF EXISTS camp_occupancy_view;
CREATE VIEW camp_occupancy_view AS
SELECT c.campid, c.campname, c.capacity,
       COALESCE(c.location, 'Central Zone') AS location,
       COUNT(v.victimid)::INTEGER AS currentoccupancy,
       (c.capacity - COUNT(v.victimid))::INTEGER AS vacantspace
FROM relief_camp c
LEFT JOIN victim v ON v.campid = c.campid
GROUP BY c.campid, c.campname, c.capacity, c.location;

-- Normalize legacy active missions so every in-progress sortie has one real drone.
WITH ranked_active AS (
    SELECT missionid,
           ROW_NUMBER() OVER (
               PARTITION BY droneid
               ORDER BY missiondate DESC, missionid DESC
           ) AS position
    FROM mission
    WHERE missionstatus = 'In Progress' AND droneid IS NOT NULL
)
UPDATE mission m
SET missionstatus = 'Planned'
FROM ranked_active r
WHERE m.missionid = r.missionid AND r.position > 1;

UPDATE mission
SET missionstatus = 'Planned'
WHERE missionstatus = 'In Progress' AND droneid IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS mission_one_active_per_drone_idx
ON mission (droneid)
WHERE missionstatus = 'In Progress' AND droneid IS NOT NULL;

