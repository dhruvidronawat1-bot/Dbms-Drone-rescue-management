-- PostgreSQL schema used by the deployed Spring/JDBC application.
-- The original Oracle coursework scripts remain unchanged in this folder.

CREATE TABLE IF NOT EXISTS operator (
    operatorid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(30) NOT NULL,
    lastname VARCHAR(30),
    licenseno VARCHAR(40) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS drone (
    droneid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model VARCHAR(60) NOT NULL,
    manufacturer VARCHAR(60) NOT NULL DEFAULT 'Unknown',
    payloadcapacity NUMERIC(7,2) NOT NULL DEFAULT 0 CHECK (payloadcapacity >= 0),
    maxflighttime INTEGER NOT NULL DEFAULT 40 CHECK (maxflighttime > 0),
    batterylevel INTEGER CHECK (batterylevel BETWEEN 0 AND 100),
    status VARCHAR(30) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'On Mission', 'Charging', 'Under Maintenance')),
    operatorid BIGINT REFERENCES operator(operatorid)
);

