ALTER TABLE drone ADD COLUMN IF NOT EXISTS payloadcapacity NUMERIC(7,2) NOT NULL DEFAULT 0;
ALTER TABLE drone ADD COLUMN IF NOT EXISTS maxflighttime INTEGER NOT NULL DEFAULT 40;
ALTER TABLE drone DROP CONSTRAINT IF EXISTS drone_status_check;
ALTER TABLE drone ADD CONSTRAINT drone_status_check
    CHECK (status IN ('Available', 'On Mission', 'Charging', 'Under Maintenance'));

CREATE TABLE IF NOT EXISTS location (
    locationid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    areaname VARCHAR(80) NOT NULL,
    district VARCHAR(60),
    state VARCHAR(60),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6)
);

CREATE TABLE IF NOT EXISTS disaster (
    disasterid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disastername VARCHAR(80) NOT NULL,
    startdate DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Contained', 'Closed')),
    locationid BIGINT NOT NULL REFERENCES location(locationid)
);

CREATE TABLE IF NOT EXISTS relief_camp (
    campid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campname VARCHAR(80) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    contactno VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS victim (
    victimid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    victimname VARCHAR(80) NOT NULL,
    dateofbirth DATE,
    gender CHAR(1) CHECK (gender IN ('M', 'F', 'O')),
    medicalpriority VARCHAR(15) CHECK (medicalpriority IN ('Low', 'Medium', 'High', 'Critical')),
    currentstatus VARCHAR(20) NOT NULL DEFAULT 'Missing'
        CHECK (currentstatus IN ('Missing', 'Rescued', 'In Camp', 'Hospitalized', 'Discharged')),
    disasterid BIGINT NOT NULL REFERENCES disaster(disasterid),
    campid BIGINT REFERENCES relief_camp(campid) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS mission (
    missionid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    missiontype VARCHAR(30),
    missiondate DATE NOT NULL DEFAULT CURRENT_DATE,
    priority VARCHAR(15) NOT NULL DEFAULT 'Medium',
    missionstatus VARCHAR(30) NOT NULL DEFAULT 'Planned',
    disasterid BIGINT REFERENCES disaster(disasterid),
    droneid BIGINT REFERENCES drone(droneid),
    operatorid BIGINT REFERENCES operator(operatorid)
);

ALTER TABLE mission ADD COLUMN IF NOT EXISTS priority VARCHAR(15) NOT NULL DEFAULT 'Medium';

CREATE TABLE IF NOT EXISTS supply (
    supplyid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplytype VARCHAR(60) NOT NULL,
    quantityavailable INTEGER NOT NULL DEFAULT 0 CHECK (quantityavailable >= 0),
    campid BIGINT REFERENCES relief_camp(campid)
);

CREATE OR REPLACE VIEW camp_occupancy_view AS
SELECT c.campid, c.campname, c.capacity,
       COUNT(v.victimid)::INTEGER AS currentoccupancy,
       (c.capacity - COUNT(v.victimid))::INTEGER AS vacantspace
FROM relief_camp c
LEFT JOIN victim v ON v.campid = c.campid
GROUP BY c.campid, c.campname, c.capacity;

